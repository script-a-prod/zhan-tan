import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createEngine, normalize } from '../src/js/chat-engine.js';

const ru = JSON.parse(await readFile(new URL('../src/data/kb.ru.json', import.meta.url)));
const kk = JSON.parse(await readFile(new URL('../src/data/kb.kk.json', import.meta.url)));

async function asks(kb, lang, question, expected, actionType) {
  const answer = await createEngine({ kb, lang }).reply(question);
  assert.match(answer.text, expected);
  if (actionType) assert.ok(answer.actions?.some((action) => action.type === actionType));
}

test('normalization handles case, ё, punctuation and spaces', () => {
  assert.equal(normalize('  ЁЛКА!!!  и   вода? '), 'елка и вода');
});

test('greeting and suggestions work in both languages', () => {
  const ruEngine = createEngine({ kb: ru, lang: 'ru' });
  const kkEngine = createEngine({ kb: kk, lang: 'kk' });
  assert.match(ruEngine.greet().text, /Здравствуйте/);
  assert.equal(ruEngine.suggestions().length, 4);
  assert.match(kkEngine.greet().text, /Сәлеметсіз/);
});

